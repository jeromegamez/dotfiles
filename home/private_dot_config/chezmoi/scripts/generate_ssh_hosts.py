#!/usr/bin/env python3

import json
import re
import sys
from urllib.parse import urlsplit

HOST_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
HOSTNAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9.:-]*$")
USER_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._@-]*$")
FINGERPRINT_RE = re.compile(
    r"^(SHA256:[A-Za-z0-9+/=]+|([0-9a-fA-F]{2}:){15}[0-9a-fA-F]{2})$"
)


def sanitize_title(raw_title: object) -> str:
    if not isinstance(raw_title, str):
        return "Untitled"
    cleaned = re.sub(r"[\r\n\x00-\x1f\x7f]+", " ", raw_title).strip()
    return cleaned or "Untitled"


def extract_fields(item: dict) -> dict[str, str]:
    fields: dict[str, str] = {}
    for field in item.get("fields") or []:
        if not isinstance(field, dict):
            continue
        label = field.get("label")
        value = field.get("value")
        if not isinstance(label, str) or not isinstance(value, str):
            continue
        key = label.strip().lower()
        val = value.strip()
        if key and val and key not in fields:
            fields[key] = val
    return fields


def extract_ssh_url(item: dict) -> str | None:
    for field in item.get("fields") or []:
        if not isinstance(field, dict):
            continue
        if field.get("type") == "URL" and isinstance(field.get("value"), str):
            candidate = field["value"].strip()
            if candidate.lower().startswith("ssh://"):
                return candidate

    for entry in item.get("urls") or []:
        if not isinstance(entry, dict):
            continue
        href = entry.get("href")
        if isinstance(href, str):
            candidate = href.strip()
            if candidate.lower().startswith("ssh://"):
                return candidate

    return None


def main() -> None:
    raw_items = json.load(sys.stdin)
    items = sorted(
        (item for item in raw_items if isinstance(item, dict)),
        key=lambda item: (
            item.get("title", "").lower() if isinstance(item.get("title"), str) else ""
        ),
    )

    print("# Generated by chezmoi from 1Password SSH Key items.")
    print("# Schema:")
    print("#   - URL field: ssh://user@host")
    print(
        "#   - optional hostname field: actual target host/IP when different from the SSH alias"
    )
    print("#   - optional port field")
    print("# Do not edit manually.")
    print()

    seen_hosts: set[str] = set()

    for item in items:
        title = sanitize_title(item.get("title"))
        url = extract_ssh_url(item)
        if not url:
            continue

        try:
            parsed = urlsplit(url)
            url_port = parsed.port
        except ValueError:
            print(
                f"Warning: Skipping 1Password item {title!r} with invalid SSH URL",
                file=sys.stderr,
            )
            continue

        if (
            parsed.scheme.lower() != "ssh"
            or parsed.path not in ("", "/")
            or parsed.query
            or parsed.fragment
            or parsed.password is not None
            or not parsed.hostname
        ):
            print(
                f"Warning: Skipping 1Password item {title!r} with unsupported SSH URL",
                file=sys.stderr,
            )
            continue

        fields = extract_fields(item)
        host = parsed.hostname
        hostname = fields.get("hostname")
        user = fields.get("user") or parsed.username
        port_str = fields.get("port") or (
            str(url_port) if url_port is not None else None
        )
        fingerprint = fields.get("fingerprint")

        if not (host and user and fingerprint):
            continue

        if not HOST_RE.match(host):
            print(
                f"Warning: Skipping 1Password item {title!r} with invalid Host alias",
                file=sys.stderr,
            )
            continue

        if hostname is not None and not HOSTNAME_RE.match(hostname):
            print(
                f"Warning: Skipping 1Password item {title!r} with invalid HostName",
                file=sys.stderr,
            )
            continue

        if not USER_RE.match(user):
            print(
                f"Warning: Skipping 1Password item {title!r} with invalid User",
                file=sys.stderr,
            )
            continue

        if not FINGERPRINT_RE.match(fingerprint):
            print(
                f"Warning: Skipping 1Password item {title!r} with invalid fingerprint",
                file=sys.stderr,
            )
            continue

        port: int | None = None
        if port_str is not None:
            if not port_str.isdigit():
                print(
                    f"Warning: Skipping 1Password item {title!r} with non-numeric Port",
                    file=sys.stderr,
                )
                continue
            port = int(port_str)
            if not (1 <= port <= 65535):
                print(
                    f"Warning: Skipping 1Password item {title!r} with out-of-range Port",
                    file=sys.stderr,
                )
                continue

        if host in seen_hosts:
            print(
                f"Warning: Skipping duplicate SSH Host {host!r} from 1Password item {title!r}",
                file=sys.stderr,
            )
            continue
        seen_hosts.add(host)

        identity_file = fingerprint.replace(":", "_").replace("/", "_")

        print(f"# 1Password Item: {title}")
        print(f"Host {host}")
        if hostname:
            print(f"    HostName {hostname}")
        print(f"    User {user}")
        print("    IdentitiesOnly yes")
        print(f"    IdentityFile ~/.ssh/1Password/{identity_file}.pub")
        if port is not None:
            print(f"    Port {port}")
        print()


if __name__ == "__main__":
    main()
