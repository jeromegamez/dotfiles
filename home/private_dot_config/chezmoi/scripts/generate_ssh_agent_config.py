#!/usr/bin/env python3

from __future__ import annotations

import argparse
import json
import re
import sys

ACCOUNT_UUID_RE = re.compile(r"^[A-Za-z0-9]{26}\Z")
CONTROL_CHAR_RE = re.compile(r"[\x00-\x1f\x7f]")


def normalize_host(value: str) -> str:
    lowered = value.strip().lower()
    for prefix in ("https://", "http://"):
        if lowered.startswith(prefix):
            lowered = lowered[len(prefix) :]
            break
    return lowered.rstrip("/")


def resolve_account_uuid(accounts: list[object], selector: str) -> str:
    query = selector.strip()
    if not query:
        raise ValueError("1Password account selector must not be empty")

    query_lower = query.lower()
    query_host = normalize_host(query)

    exact_matches: list[dict[str, object]] = []
    fallback_matches: list[dict[str, object]] = []

    for entry in accounts:
        if not isinstance(entry, dict):
            continue

        account_uuid = entry.get("account_uuid")
        user_uuid = entry.get("user_uuid")
        shorthand = entry.get("shorthand")
        url = entry.get("url")
        email = entry.get("email")

        exact_candidates = set()
        for raw in (account_uuid, user_uuid, shorthand):
            if isinstance(raw, str) and raw.strip():
                exact_candidates.add(raw.strip().lower())
        if isinstance(url, str) and url.strip():
            exact_candidates.add(url.strip().lower())
            exact_candidates.add(normalize_host(url))

        if query_lower in exact_candidates or query_host in exact_candidates:
            exact_matches.append(entry)
            continue

        fallback_candidates = set()
        if isinstance(url, str) and url.strip():
            host = normalize_host(url)
            if "." in host:
                fallback_candidates.add(host.split(".", 1)[0])
        if isinstance(email, str) and email.strip():
            fallback_candidates.add(email.strip().lower())

        if query_lower in fallback_candidates:
            fallback_matches.append(entry)

    matches = exact_matches or fallback_matches
    if not matches:
        raise ValueError(
            f"No signed-in 1Password account matched {selector!r}; sign in or update onepasswordAccount"
        )
    if len(matches) > 1:
        raise ValueError(
            f"Multiple 1Password accounts matched {selector!r}; set onepasswordAccount to a sign-in address or account UUID"
        )

    resolved = matches[0].get("account_uuid")
    if not isinstance(resolved, str) or not ACCOUNT_UUID_RE.match(resolved.strip()):
        raise ValueError(f"Matched 1Password account for {selector!r} has an invalid account_uuid")
    return resolved.strip()


def render_agent_config(account_uuid: str, vault: str) -> str:
    clean_uuid = account_uuid.strip()
    clean_vault = vault.strip()
    if not ACCOUNT_UUID_RE.match(clean_uuid):
        raise ValueError("Invalid 1Password account UUID")
    if not clean_vault or CONTROL_CHAR_RE.search(clean_vault):
        raise ValueError("Invalid 1Password vault name")

    # JSON double-quoted strings are valid TOML basic strings.
    return (
        "# Generated by chezmoi. Do not edit manually.\n"
        "[[ssh-keys]]\n"
        f"account = {json.dumps(clean_uuid)}\n"
        f"vault = {json.dumps(clean_vault)}\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate 1Password SSH agent.toml scoped to one account and vault."
    )
    parser.add_argument("--account", required=True, help="Configured 1Password account selector")
    parser.add_argument("--vault", required=True, help="1Password vault name for SSH keys")
    args = parser.parse_args(argv)

    raw_accounts = json.load(sys.stdin)
    if not isinstance(raw_accounts, list):
        raise ValueError("Expected JSON array from `op account list --format json`")

    account_uuid = resolve_account_uuid(raw_accounts, args.account)
    sys.stdout.write(render_agent_config(account_uuid, args.vault))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except ValueError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        raise SystemExit(1)
